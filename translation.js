// Greeting based on time
function getGreeting(lang) {
  const now = new Date();
  const hour = now.getHours();
  let period;
  if (hour >= 5 && hour < 12) {
    period = "morning";
  } else if (hour >= 12 && hour < 17) {
    period = "afternoon";
  } else if (hour >= 17 && hour < 21) {
    period = "evening";
  } else {
    period = "night";
  }
  return translations.greetings[lang][period];
}


function initLanguage(){
  // detecting current lang
  let currentLang = localStorage.getItem('language') || 'en';
  console.log(`current lang: ${currentLang}`);
  setLanguage(currentLang);

  document.getElementById("lang-toggle").addEventListener("click", () => {
      currentLang = currentLang === 'en' ? 'ar' : 'en';
      localStorage.setItem('language', currentLang);
      setLanguage(currentLang);
    });
  }

window.addEventListener("DOMContentLoaded", initLanguage);

// Enhanced translation function that handles both innerHTML and innerText
function setLanguage(lang) {
  const html = document.getElementById("html");
  // Set direction and language attribute
  html.setAttribute("lang", lang);
  html.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
  console.log(`current lang2: ${lang}`);

  // Translate all elements with data-key attribute
  document.querySelectorAll("[data-key]").forEach(el => {
    const key = el.getAttribute("data-key");
    const contentType = el.getAttribute("data-content-type") || "html"; // text or html

    if (translations[lang] && translations[lang][key]) {
      if (contentType === "html") {
        el.innerHTML = translations[lang][key];
      } else {
        el.textContent = translations[lang][key].replace(/<br\s*\/?>/gi, "\n")
        ;
      }
    }  
  });

  // Handle special cases
  const searchInput = document.querySelector('input[data-key="searchBar"]');
  if (searchInput) {
    searchInput.placeholder = translations[lang].searchBar;
  }

  const searchData = document.querySelector('input[data-key="searchData"]');
  if (searchData) {
    searchData.placeholder = translations[lang].searchData;
  }
  const greetingMessage = document.getElementById("greetingMessage");
  if (greetingMessage) {
    greetingMessage.innerText = getGreeting(lang) + ', ';
  }

  const arrows = document.querySelectorAll(".fa-arrow-right");
  arrows.forEach(arrow => {
    arrow.style.transform = lang === "ar" ? "rotate(180deg)" : "rotate(0deg)";
  });
  
  // Translate dynamically created content
  // translateDynamicContent(lang);
}

